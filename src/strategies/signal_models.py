"""
signal_models.py
Standardized data contracts for strategy signals, multi-leg order requests, and exit events.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional, Dict, Any
import time
import uuid

class StrategyMode(Enum):
    """Independent operating mode per strategy."""
    DISABLED = "DISABLED"
    MONITOR_ONLY = "MONITOR_ONLY"
    PAPER = "PAPER"

class SignalDirection(Enum):
    """Direction of generated strategy signal."""
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    BULLISH = "BUY"
    BEARISH = "SELL"
    NEUTRAL = "HOLD"

class ExitReason(Enum):
    """Exhaustive exit reason enumeration."""
    STOP_LOSS = "STOP_LOSS"
    STOP_LOSS_HIT = "STOP_LOSS"
    TRAILING_STOP_LOSS = "TRAILING_STOP_LOSS"
    PROFIT_TARGET = "PROFIT_TARGET"
    TARGET_HIT = "PROFIT_TARGET"
    SIGNAL_REVERSAL = "SIGNAL_REVERSAL"
    TIME_CUTOFF = "TIME_CUTOFF"
    MAX_HOLDING_TIME = "MAX_HOLDING_TIME"
    SAFETY_EXIT = "SAFETY_EXIT"
    DATA_QUALITY_EXIT = "DATA_QUALITY_EXIT"
    EMERGENCY_SHUTDOWN = "EMERGENCY_SHUTDOWN"

class StopLossPolicy(Enum):
    """Exit evaluation policy for multi-leg structures."""
    COMBINED_POSITION = "COMBINED_POSITION"
    INDIVIDUAL_LEG = "INDIVIDUAL_LEG"
    INDIVIDUAL_LEG_WITH_SHIFT_TO_COST = "INDIVIDUAL_LEG_WITH_SHIFT_TO_COST"
    UNDERLYING_TRIGGER = "UNDERLYING_TRIGGER"
    TIME_BASED = "TIME_BASED"
    HYBRID = "HYBRID"
    PREMIUM_BASED = "PREMIUM_BASED"
    STRUCTURE_BASED = "STRUCTURE_BASED"

@dataclass
class LegOrder:
    """Represents a single leg within a multi-leg order signal."""
    leg_id: str = ""
    symbol: str = ""
    strike: float = 0.0
    option_type: str = "CE"                  # "CE", "PE", or "FUT"
    expiry: str = ""
    side: str = "BUY"                        # "BUY" or "SELL"
    quantity: int = 65
    requested_price: float = 0.0
    assumed_fill_price: float = 0.0
    status: str = "PENDING"                  # "PENDING", "FILLED", "REJECTED"

    def __post_init__(self):
        if not self.leg_id:
            self.leg_id = str(uuid.uuid4())[:6]

@dataclass
class StrategySignal:
    """Signal generated by an independent strategy evaluation."""
    strategy_id: str
    direction: SignalDirection
    timestamp: str
    legs: List[LegOrder]
    signal_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    strategy_version: str = "1.0.0"
    entry_reason: str = ""
    initial_sl_value: float = 0.0
    initial_sl_type: str = "PERCENTAGE" # "PERCENTAGE", "POINTS", "COMBINED"
    trailing_sl_value: float = 0.0
    target_value: float = 0.0
    target_type: str = "PERCENTAGE"
    exit_policy: StopLossPolicy = StopLossPolicy.COMBINED_POSITION
    metadata: Dict[str, Any] = field(default_factory=dict)
    rejection_reason: Optional[str] = None

@dataclass
class ExitSignal:
    """Explicit order request to exit an open position or leg."""
    position_id: str
    strategy_id: str
    timestamp: str
    reason: ExitReason
    legs_to_close: List[str] = field(default_factory=list) # Leg IDs to close, empty means entire position
    exit_price_reference: float = 0.0
    details: str = ""
    signal_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    leg_quantities: Dict[str, int] = field(default_factory=dict) # Leg ID -> quantity to exit (empty = all remaining)
